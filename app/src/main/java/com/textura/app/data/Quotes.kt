    val categories: List<String> get() = byCategory.keys.toList()

    val all: List<Quote> by lazy { byCategory.values.flatten().distinctBy { it.text } }

    private val daily: List<Quote> get() = byCategory["Wisdom"].orEmpty() + byCategory["Proverbs"].orEmpty() + byCategory["Motivation"].orEmpty()

    fun ofTheDay(): Quote = daily[(LocalDate.now().dayOfYear + LocalDate.now().year) % daily.size]

    fun random(category: String? = null, except: String? = null): Quote =
        (byCategory[category] ?: all).filter { it.text != except }.random()
}
